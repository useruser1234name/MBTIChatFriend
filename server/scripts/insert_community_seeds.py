async def insert_seeds():
    await initialize_pool()
    async with (await __import__("app.postgres_async", fromlist=["_pool"])._pool.acquire()) as conn:
        inserted = 0
        for mbti, posts in SEED_POSTS.items():
            for post in posts:
                await conn.execute(
                    """
                    INSERT INTO community_posts (user_id, mbti, content, anonymous_name)
                    VALUES ($1, $2, $3, $4)
                    ON CONFLICT DO NOTHING
                    """,
                    f"seed_ai_{mbti.lower()}",
                    mbti,
                    post["content"],
                    f"{mbti} AI 시드",
                )
                inserted += 1
        print(f"시드 콘텐츠 {inserted}건 삽입 완료")

if __name__ == "__main__":
    asyncio.run(insert_seeds())
